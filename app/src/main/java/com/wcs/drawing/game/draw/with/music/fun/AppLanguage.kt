// The fallback preserves drawing names, filenames, musical keys and detailed diagnostics.
@Composable
fun uiText(english:String):String {
    val language=LocalAppLanguage.current
    val extraIndex=when(language) {
        AppLanguage.GERMAN->0;AppLanguage.FRENCH->1;AppLanguage.SPANISH->2;AppLanguage.CHINESE->3
        else->null
    }
    if(extraIndex!=null) return additionalUi[english]?.get(extraIndex) ?: english
    val index=when(language) {AppLanguage.ENGLISH->return english;AppLanguage.URDU->0;AppLanguage.HINDI->1;AppLanguage.ARABIC->2;else->return english}
    return translatedUi[english]?.get(index) ?: english
}
